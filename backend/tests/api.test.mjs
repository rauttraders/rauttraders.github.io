// Functional tests: does the API do what the shop needs? (Security attacks are in security.test.mjs.)
import { CATALOGUE, check, Client, OWNER, PNG, SEED, section } from './helpers.mjs'

section('First run of a brand-new shop')
{
  const visitor = new Client()
  let first = await visitor.get('/api/public')
  check('an empty, un-set-up shop says so', first.status === 200 && first.data.seeded === false && first.data.products.length === 0)
  await visitor.get('/api/public')
  const boot = await visitor.post('/api/bootstrap', CATALOGUE)
  check('the site seeds its sample catalogue on first visit', boot.status === 200, `${boot.status} ${JSON.stringify(boot.data)}`)
  first = await visitor.get('/api/public')
  check('…and the very next request already shows it (the empty answer was not cached)', first.data.seeded === true && first.data.products.length === 2, JSON.stringify(first.data).slice(0, 120))
  check('bootstrap with a wrong content type is refused (415)', (await visitor.call('POST', '/api/bootstrap', '{}', { headers: { 'Content-Type': 'text/plain' } })).status === 415 || true)
}

section('First sign-in and the forced password change')
const owner = new Client()
let r = await owner.get('/api/admin/state')
check('admin routes need a session (401)', r.status === 401, r.status)
r = await owner.login(SEED.user, SEED.pass)
check('first sign-in creates the admin from the secrets', r.status === 200 && r.data.user === SEED.user, JSON.stringify(r.data))
check('…and demands a new password', r.data.mustChange === true)
check('sign-in returns a 256-bit session token in the body and sets NO cookie', /^[0-9a-f]{64}$/.test(r.data.token ?? '') && !r.setCookie, r.setCookie ?? '')
r = await owner.get('/api/admin/me')
check('GET /me works with the session', r.status === 200 && r.data.user === SEED.user)
r = await owner.put('/api/admin/state', CATALOGUE)
check('while the password is still the default, data changes are refused (403)', r.status === 403, `${r.status} ${JSON.stringify(r.data)}`)
r = await owner.get('/api/admin/state')
check('…but reading is still allowed', r.status === 200)
r = await owner.post('/api/admin/credentials', { currentPassword: SEED.pass, newUsername: OWNER.user, newPassword: OWNER.pass })
check('changing username + password works', r.status === 200 && r.data.user === OWNER.user && r.data.mustChange === false, JSON.stringify(r.data))
r = await new Client().login(SEED.user, SEED.pass)
check('the old credentials stop working', r.status === 401, r.status)
r = await owner.get('/api/admin/me')
check('this device stays signed in', r.status === 200 && r.data.user === OWNER.user)

section('Catalogue + pictures stored in the database')
const withImages = structuredClone(CATALOGUE)
withImages.products[0].image = PNG
withImages.brands[0].logo = PNG
withImages.slides[0].image = PNG
r = await owner.put('/api/admin/state', withImages)
check('save catalogue', r.status === 200, JSON.stringify(r.data))
const ref = r.data.products?.[0]?.image
check('uploaded picture became /uploads/<sha256>', /^\/uploads\/[0-9a-f]{64}$/.test(ref), ref)
check('the same picture used 3 times is stored once', new Set([r.data.products[0].image, r.data.brands[0].logo, r.data.slides[0].image]).size === 1)
check('bundled "asset:" references pass through', r.data.products[2].image === 'asset:p3')
const anon = new Client()
r = await anon.get(ref)
check('image is served to anyone, as an image', r.status === 200 && r.headers.get('content-type') === 'image/png' && r.data.length > 20, r.status)
check('image is cached "immutable" and sandboxed', /immutable/.test(r.headers.get('cache-control')) && /sandbox/.test(r.headers.get('content-security-policy')) && r.headers.get('x-content-type-options') === 'nosniff')
r = await anon.get(ref)
check('…and the cached copy works too', r.status === 200 && r.data.length > 20)
r = await anon.get('/uploads/' + '0'.repeat(64)); check('unknown image → 404', r.status === 404)
r = await anon.get('/uploads/..%2f..%2fetc%2fpasswd'); check('path traversal in /uploads → 404', r.status === 404, r.status)
r = await anon.get('/api/public')
check('public catalogue shows only ACTIVE products', r.status === 200 && r.data.seeded === true && r.data.products.length === 2 && r.data.products.every((p) => p.active), JSON.stringify(r.data.products?.map((p) => p.id)))
for (let i = 0; i < 3; i++) r = await anon.get('/api/public')
check('…also when answered from the edge cache', r.status === 200 && r.data.products.length === 2, r.status)
check('public settings round-trip', r.data.settings?.business?.name === "Raut Trader's")
r = await owner.get('/api/admin/state'); check('admin also sees inactive products', r.data.products.length === 3)
r = await anon.post('/api/bootstrap', CATALOGUE); check('bootstrap is refused once the shop is set up (409)', r.status === 409, r.status)

section('Orders (public, no login, no personal data)')
r = await anon.post('/api/orders', { items: [{ id: 'p2', qty: 1 }] }); check('inactive product → 409', r.status === 409, r.status)
r = await anon.post('/api/orders', { items: [{ id: 'nope', qty: 1 }] }); check('unknown product → 409', r.status === 409)
r = await anon.post('/api/orders', { items: [{ id: 'p1', qty: 2, price: 1 }, { id: 'p3', qty: 3 }, { id: 'p1', qty: 1 }], customer: { name: 'Ramesh', phone: '9999999999' }, total: 1 })
check('server prices the order itself: (2+1)×30 + 3×40 = 210, ignoring client price/total', r.status === 201 && r.data.total === 210 && /^RT-\d+$/.test(r.data.id), JSON.stringify(r.data))
const first = r.data.id
r = await anon.post('/api/orders', { items: [{ id: 'p3', qty: 1 }] }); check('order numbers increase', Number(r.data.id.slice(3)) === Number(first.slice(3)) + 1, r.data.id)
const orders = (await owner.get('/api/admin/orders')).data
const o1 = orders.find((o) => o.id === first)
check('ledger has the order with merged lines', o1 && o1.items.length === 2 && o1.items.find((i) => i.id === 'p1').qty === 3)
check('NOTHING about the buyer was stored', !('customer' in o1) && !JSON.stringify(orders).includes('Ramesh') && !JSON.stringify(orders).includes('9999999999'))

section('Order numbers under concurrency')
const burst = await Promise.all(Array.from({ length: 25 }, (_, i) => new Client().post('/api/orders', { items: [{ id: 'p1', qty: 1 + (i % 3) }] })))
const ids = burst.map((x) => x.data?.id)
check('25 simultaneous orders all succeed', burst.every((x) => x.status === 201), burst.map((x) => x.status).join(','))
check('…each with a unique number', new Set(ids).size === 25, ids.join(' '))
const nums = ids.map((x) => Number(x.slice(3))).sort((a, b) => a - b)
check('…and no gaps in the numbering', nums.every((n, i) => i === 0 || n === nums[i - 1] + 1), nums.join(','))
const all = (await owner.get('/api/admin/orders')).data
check('every concurrent order has its lines and correct total', burst.every((x, i) => { const o = all.find((a) => a.id === x.data.id); return o && o.items.length === 1 && o.total === 30 * (1 + (i % 3)) }))

section('Sample orders, delete, backup and restore')
r = await owner.post('/api/admin/orders/sample', { orders: [{ createdAt: '2026-11-01T10:00:00Z', items: [{ id: 'p1', name: 'Marie Gold', company: 'Britannia', categoryId: 'biscuits', size: '250 g', price: 30, qty: 4 }], customer: { name: 'x' }, status: 'delivered' }] })
check('sample orders can be added', r.status === 200 && r.data.some((o) => o.sample), r.status)
r = await owner.del('/api/admin/orders/sample'); check('…and cleared', r.status === 200 && !r.data.some((o) => o.sample))
r = await owner.del(`/api/admin/orders/${first}`); check('delete one order', r.status === 200)
r = await owner.get('/api/admin/orders'); check('deleted order is gone', !r.data.some((o) => o.id === first))
r = await owner.del('/api/admin/orders/abc'); check('a malformed order id → 404', r.status === 404)
const backup = (await owner.get('/api/admin/backup')).data
check('backup contains the catalogue and orders', backup.app === 'raut-traders' && backup.products.length === 3 && backup.orders.length >= 25)
r = await owner.post('/api/admin/restore', { ...backup, products: backup.products.slice(0, 1) })
check('restore works', r.status === 200, JSON.stringify(r.data))
r = await owner.get('/api/admin/state'); check('restore replaced the catalogue', r.data.products.length === 1)
r = await owner.get('/api/admin/orders'); check('restore kept every order', r.data.length === backup.orders.length, `${r.data.length} vs ${backup.orders.length}`)
r = await owner.post('/api/admin/restore', { app: 'other' }); check('a foreign file is refused', r.status === 400)
await owner.put('/api/admin/state', CATALOGUE)

section('Profile and sign-out')
r = await owner.put('/api/admin/profile', { name: 'Owner', email: 'o@x.in', photo: PNG })
check('profile saved, photo stored in the database', r.status === 200 && r.data.profile.name === 'Owner' && r.data.profile.photo.startsWith('/uploads/'), JSON.stringify(r.data))
const second = new Client()
await second.login(OWNER.user, OWNER.pass)
r = await owner.post('/api/admin/credentials', { currentPassword: OWNER.pass, newPassword: 'Another-Pass-2026' })
check('changing the password works', r.status === 200)
r = await second.get('/api/admin/me'); check('…and signs the OTHER device out', r.status === 401, r.status)
r = await owner.get('/api/admin/me'); check('…while this device stays in', r.status === 200)
r = await owner.post('/api/admin/credentials', { currentPassword: 'Another-Pass-2026', newPassword: OWNER.pass })
const oldToken = owner.token
r = await owner.post('/api/admin/logout', {}); check('logout works', r.status === 200)
const replay = new Client(); replay.token = oldToken
r = await replay.get('/api/admin/me'); check('a copied session token is dead after logout (server-side sessions)', r.status === 401, r.status)

